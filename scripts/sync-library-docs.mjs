// Keeps the course list in README.md ("Course library") in sync with server/library/*.json.
//   npm run library:docs            (rewrites the block between the library:start and library:end markers)
//   npm run library:docs -- --check (exit 1 if the README is out of date; test/library.test.js does the same)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadBuiltin } from '../server/library.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..'), README = path.join(ROOT, 'README.md');
const START = '<!-- library:start (generated by "npm run library:docs", do not edit by hand) -->', END = '<!-- library:end -->';
const PROGRAMMES = { trial: 'trial class', 'term-1': 'term 1', 'term-2': 'term 2', 'term-3': 'term 3', holiday: 'holiday camp' };

export function render(courses = loadBuiltin(path.join(ROOT, 'server', 'library'))) {
  const rows = courses.map((c) => `| **${c.title.en}** (\`${c.id}\`) | ${c.age.min} to ${c.age.max} | ${c.sessions === 1 ? '1 session' : c.sessions + ' sessions'}, ${c.minutes[0]} to ${c.minutes[1]} min | ${c.levels.length} | ${c.programmes.map((p) => PROGRAMMES[p]).join(', ')} |`);
  const goals = courses.map((c) => `**${c.title.en}**: ${c.promise.en}\n${c.goals.en.map((g) => `- ${g}`).join('\n')}`);
  return `${START}\n| Course | Ages | Length | Levels | Programme |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}\n\nLearning goals, in plain words (the same text teachers see and can copy for parents):\n\n${goals.join('\n\n')}\n${END}`;
}
export function sync(readme, courses) {
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error('README.md has no library:start and library:end markers');
  return readme.slice(0, a) + render(courses) + readme.slice(b + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const before = fs.readFileSync(README, 'utf8'), after = sync(before);
  if (process.argv.includes('--check')) {
    if (before !== after) { console.error('README.md is out of date: run "npm run library:docs"'); process.exit(1); }
    console.log('README.md is in sync');
  } else { fs.writeFileSync(README, after); console.log(before === after ? 'already in sync' : 'README.md updated'); }
}
